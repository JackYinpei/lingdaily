package com.qcy.lingdaily.core.model

import java.util.UUID
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

@Serializable
enum class AIPracticeAction {
    @SerialName("start") START,
    @SerialName("answer") ANSWER,
    @SerialName("advance") ADVANCE,
}

@Serializable
data class AIPendingRequest(val id: Uuid, val action: AIPracticeAction)

@Serializable
data class AIFeedback(
    val revised: String,
    val meaning: String,
    val note: String,
    /** Vocabulary the learner lacked in this sentence; auto-collected into 词库. */
    val items: List<AILearningItem>? = null,
)

/** Same shape as the web `unfamiliar_english.items[]` (minus `original`). */
@Serializable
data class AILearningItem(
    val text: String,
    /** word | phrase | grammar */
    val type: String,
    val meaning: String,
) {
    val isValid: Boolean
        get() = type in setOf("word", "phrase", "grammar")
            && text.isNotBlank() && text.length <= 80
            && meaning.isNotBlank() && meaning.length <= 120
}

@Serializable
data class AIFeedbackRecord(
    /** The learner message being coached, including each retry. */
    val id: Uuid,
    val stepIndex: Int,
    val feedback: AIFeedback,
)

@Serializable
data class AIPracticeTurn(
    val reply: String,
    val translation: String,
    val hint: String,
    val keywords: String,
    val suggestedReply: String,
    val suggestedMeaning: String,
    val feedback: AIFeedback? = null,
) {
    fun isValid(action: AIPracticeAction): Boolean {
        val values = listOf(reply to 1000, translation to 1000, hint to 400, keywords to 200,
            suggestedReply to 800, suggestedMeaning to 800)
        if (!values.all { (text, limit) -> text.isNotBlank() && text.length <= limit }) return false
        if ((action == AIPracticeAction.ANSWER) != (feedback != null)) return false
        if (feedback == null) return true
        return listOf(feedback.revised to 800, feedback.meaning to 800, feedback.note to 500)
            .all { (text, limit) -> text.isNotBlank() && text.length <= limit }
            && feedback.items.orEmpty().size <= 3 && feedback.items.orEmpty().all { it.isValid }
    }
}

@Serializable
data class AIPracticeState(
    val pending: AIPendingRequest? = null,
    val turn: AIPracticeTurn? = null,
    val feedbacks: List<AIFeedbackRecord> = emptyList(),
    val model: String? = null,
)

@Serializable
data class AIPracticeRequest(
    val requestId: Uuid,
    val sessionId: Uuid,
    val action: AIPracticeAction,
    val stepIndex: Int,
    val goal: String,
    val context: String,
    val scenario: Scenario,
    val messages: List<Message>,
    /** The learner's model choice; the server only honours listed models. */
    val model: String? = null,
    /** Omitted for standard, so default requests are unchanged for older servers. */
    val level: String? = null,
    /** Omitted when following the scenario's persona. */
    val attitude: String? = null,
    val temperament: PartnerTemperament? = null,
    val reviewItems: List<ReviewTarget>? = null,
) {
    /** What the server needs to play the partner of a scenario. */
    @Serializable
    data class Scenario(
        val title: String,
        val partner: String,
        val partnerRole: String,
        val setting: String,
        val goals: List<String>,
        val persona: String? = null,
    ) {
        constructor(scenario: PracticeScenario) : this(scenario.title, scenario.partner, scenario.partnerRole,
            scenario.setting, scenario.steps.map { it.goal }, scenario.persona)
    }

    @Serializable
    data class Message(
        val role: PracticeMessage.Role,
        val kind: PracticeMessage.Kind,
        val text: String,
        val stepIndex: Int,
    )
}

@Serializable
data class AIPracticeResponse(val requestId: Uuid, val model: String, val data: AIPracticeTurn)

@Serializable
data class AIScenarioRequest(val requestId: Uuid, val description: String)

/** A learner-described scenario as generated by the server; becomes a local `PracticeScenario`. */
@Serializable
data class AIScenarioResponse(val requestId: Uuid, val model: String, val scenario: Draft) {
    @Serializable
    data class Step(
        val goal: String, val prompt: String, val translation: String, val hint: String,
        val keywords: String, val expression: String, val meaning: String,
    )

    @Serializable
    data class Draft(
        val title: String, val subtitle: String, val category: String,
        val partner: String, val partnerRole: String, val setting: String,
        val steps: List<Step>,
        /** Older servers and cached daily scenarios have none. */
        val persona: String? = null,
    ) {
        /** A validated three-step scenario, or null when any field is missing or too long. */
        fun practiceScenario(id: String): PracticeScenario? {
            val texts = listOf(title, subtitle, category, partner, partnerRole, setting) +
                steps.flatMap { listOf(it.goal, it.prompt, it.translation, it.hint, it.keywords, it.expression, it.meaning) }
            if (steps.size != 3 || !texts.all { it.isNotBlank() && it.length <= 400 }) return null
            return PracticeScenario(
                id = id, title = title, subtitle = subtitle, category = category,
                // The same placeholder iOS stores, so a synced scenario is identical on both.
                symbol = "text.bubble", partner = partner, partnerRole = partnerRole, setting = setting,
                steps = steps.mapIndexed { index, step ->
                    PracticeStep("step-$index", step.goal, step.prompt, step.translation, step.hint,
                        step.keywords, step.expression, step.meaning)
                },
                persona = PracticeScenario.cleanPersona(persona),
            )
        }
    }

    fun makeScenario(id: String = "custom-${UUID.randomUUID().toString().uppercase()}"): PracticeScenario? =
        if (model.isEmpty()) null else scenario.practiceScenario(id)
}
